import { useState } from 'react'
import { Link } from 'react-router-dom'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { AlertOctagon, AlertTriangle, BellOff, CheckCheck, Info } from 'lucide-react'
import { api, asList, type Alert } from '../api/client'
import { Card, PageHeader } from '../components/Card'
import { EmptyState } from '../components/EmptyState'
import { Segmented } from '../components/RangeSelect'
import { SkeletonRows } from '../components/Skeleton'
import { useToast } from '../components/Toast'
import { Button, Chip, ErrorBox, Toggle } from '../components/ui'
import { cx, fmtDate, fmtRel, titleCase } from '../lib/format'

type Sev = 'all' | 'critical' | 'warning' | 'info'

function SevIcon({ s }: { s: Alert['severity'] }) {
  if (s === 'critical') return <AlertOctagon className="size-4 text-rose-500" />
  if (s === 'warning') return <AlertTriangle className="size-4 text-amber-500" />
  return <Info className="size-4 text-sky-500" />
}

export default function AlertsPage() {
  const qc = useQueryClient()
  const toast = useToast()
  const [sev, setSev] = useState<Sev>('all')
  const [unreadOnly, setUnreadOnly] = useState(false)
  const q = useQuery({ queryKey: ['alerts', 'page'], queryFn: () => api.alerts(), refetchInterval: 20_000 })
  const all = asList<Alert>(q.data)
  const list = all.filter((a) => (sev === 'all' || a.severity === sev) && (!unreadOnly || !a.read))
  const unread = all.filter((a) => !a.read).length
  const count = (s: Sev) => (s === 'all' ? all.length : all.filter((a) => a.severity === s).length)

  const invalidate = () => qc.invalidateQueries({ queryKey: ['alerts'] })
  const read = useMutation({ mutationFn: (id: Alert['id']) => api.alertRead(id), onSuccess: invalidate, onError: (e) => toast(e instanceof Error ? e.message : 'Failed', 'error') })
  const readAll = useMutation({
    mutationFn: api.alertsReadAll,
    onSuccess: () => {
      toast('All alerts marked as read', 'success')
      invalidate()
    },
    onError: (e) => toast(e instanceof Error ? e.message : 'Failed', 'error'),
  })

  return (
    <div className="space-y-5">
      <PageHeader
        title="Alerts"
        subtitle={`${unread} unread · generated by watchlist monitoring, high-risk scans and feed matches`}
        actions={
          <Button icon={<CheckCheck className="size-4" />} disabled={unread === 0} loading={readAll.isPending} onClick={() => readAll.mutate()}>
            Mark all read
          </Button>
        }
      />
      <div className="flex flex-wrap items-center gap-3">
        <Segmented<Sev>
          value={sev}
          onChange={setSev}
          options={(['all', 'critical', 'warning', 'info'] as Sev[]).map((s) => ({ value: s, label: `${titleCase(s)} (${count(s)})` }))}
        />
        <Toggle checked={unreadOnly} onChange={setUnreadOnly} label="Unread only" />
      </div>
      <Card padded={false}>
        {q.error ? (
          <div className="p-4">
            <ErrorBox error={q.error} onRetry={() => q.refetch()} />
          </div>
        ) : q.isLoading ? (
          <div className="p-4">
            <SkeletonRows rows={6} />
          </div>
        ) : list.length === 0 ? (
          <EmptyState icon={<BellOff className="size-5" />} title="No alerts" description="You're all caught up." />
        ) : (
          <ul>
            {list.map((a) => (
              <li
                key={a.id}
                className={cx(
                  'flex items-start gap-3 border-b border-zinc-100 px-4 py-3 last:border-0 dark:border-zinc-800/60',
                  !a.read && 'bg-indigo-50/40 dark:bg-indigo-500/5',
                )}
              >
                <div className="mt-0.5">
                  <SevIcon s={a.severity} />
                </div>
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className={cx('text-sm', !a.read && 'font-semibold')}>{a.title}</span>
                    {a.type && <Chip>{titleCase(a.type)}</Chip>}
                    {!a.read && <span className="size-1.5 rounded-full bg-indigo-500" />}
                  </div>
                  {a.detail && <div className="mt-0.5 break-words text-xs text-zinc-600 dark:text-zinc-400">{a.detail}</div>}
                  <div className="mt-1 flex flex-wrap items-center gap-3 text-xs text-zinc-500">
                    <span title={fmtDate(a.created_at)}>{fmtRel(a.created_at)}</span>
                    {a.scan_id != null && (
                      <Link to={`/scans/${a.scan_id}`} className="text-indigo-600 hover:underline dark:text-indigo-400">
                        View scan
                      </Link>
                    )}
                    {a.watch_id != null && (
                      <Link to="/watchlist" className="text-indigo-600 hover:underline dark:text-indigo-400">
                        Watchlist
                      </Link>
                    )}
                  </div>
                </div>
                {!a.read && (
                  <Button size="sm" variant="ghost" loading={read.isPending && read.variables === a.id} onClick={() => read.mutate(a.id)}>
                    Mark read
                  </Button>
                )}
              </li>
            ))}
          </ul>
        )}
      </Card>
    </div>
  )
}
